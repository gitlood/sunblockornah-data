"""One-off: regenerate pipeline/uvpipe/cities.py and the app repo's BundledCities.kt (set APP_REPO) from GeoNames.

Usage: python build_cities.py cities5000.txt
Source: GeoNames cities5000 dump (https://download.geonames.org/export/dump/), CC BY 4.0.
Keeps every id in uvpipe/cities.py (favourites, widgets and alerts store ids), then adds
each AU/NZ place of 5,000+ people that is not within MIN_KM (METRO_KM near big cities, 30 km) of a kept place. The UV
grid is 0.4 deg (about 44 km), so places closer than that share a cell and add nothing.
Output is sorted by population, largest first; the app uses list order as marker rank.
Not run by the job or the tests.
"""
import math
import os
import re
import sys
import unicodedata

from uvpipe.cities import CITIES

MIN_POP = 5000
MIN_KM = 15
METRO_POP, METRO_KM = 250_000, 30  # suburbs of a big city are not separate towns
# Cities in their own right that sit inside a bigger city's radius.
KEEP = {"Lower Hutt", "Porirua", "Upper Hutt", "Caloundra"}
# GeoNames rows that are not towns (regions, council areas, duplicate suburbs, bad rows).
SKIP = {"Kosciuszko National Park", "Papatowai", "Waikowhai", "Red Hill", "Manukau City", "Pittwater",
        "Blue Mountains", "Central Coast", "Logan City", "Tuggeranong", "City of Port Phillip",
        "North Shore", "Adelaide Hills"}
TZ_FIX = {"Australia/Lindeman": "Australia/Brisbane", "Australia/Currie": "Australia/Hobart",
          "Australia/Eucla": "Australia/Perth", "Australia/Melbourne": "Australia/Melbourne"}
# Not in GeoNames 5000+, or too small: population for kept legacy ids.
LEGACY_POP = {"ldh": 380, "lau": 100}
POP_FIX = {"wga": 57000}  # GeoNames has only a 7,690 section for Wagga Wagga
HERE = os.path.dirname(os.path.abspath(__file__))
# APP_REPO: checkout of gitlood/SunblockorNah (private); default is a sibling dir.
APP = os.environ.get("APP_REPO", os.path.join(HERE, "..", "..", "SunblockorNah"))
KT = os.path.join(APP, "shared", "src", "commonMain", "kotlin", "com", "progressivezen",
                  "sunblockornah", "domain", "BundledCities.kt")


def in_region(lat, lon):
    """Mirror of RegionBounds.kt."""
    box = lambda a, b, c, d: a <= lat <= b and c <= lon <= d
    inc = (box(-44.0, -10.5, 113.0, 154.0) or box(-31.8, -31.4, 158.9, 159.3)
           or box(-47.5, -34.0, 166.0, 178.7) or box(-44.5, -43.5, -177.2, -175.5))
    exc = box(-12.0, 0.0, 118.0, 129.0) or box(-12.5, 0.0, 144.0, 154.0)
    return inc and not exc


def km(a, b):
    p = math.pi / 180
    x = (b[1] - a[1]) * p * math.cos((a[0] + b[0]) / 2 * p)
    return 6371 * math.hypot(x, (b[0] - a[0]) * p)


def slug(name, taken):
    s = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode().lower()
    s = re.sub(r"[^a-z0-9]+", "_", s).strip("_")
    n, out = 2, s
    while out in taken:
        out, n = f"{s}_{n}", n + 1
    return out


def parse(path):
    """GeoNames rows for AU/NZ places over the population floor: (name, lat, lon, tz, pop), largest first."""
    rows = []
    for line in open(path, encoding="utf-8"):
        f = line.split("\t")
        if f[8] in ("AU", "NZ") and int(f[14]) >= MIN_POP:
            tz = TZ_FIX.get(f[17], f[17])
            rows.append((f[1], round(float(f[4]), 2), round(float(f[5]), 2), tz, int(f[14])))
    rows.sort(key=lambda r: -r[4])
    return rows


def select(rows, legacy=CITIES):
    """Pick the places: every legacy id, then each row outside the spacing rule. Returns (kept, dropped)."""
    rows = sorted(rows, key=lambda r: -r[4])
    kept = {}
    for cid, (name, lat, lon, tz) in ((c, v[:4]) for c, v in legacy.items()):
        near = [r[4] for r in rows if r[0] == name or km((lat, lon), (r[1], r[2])) < 10]
        kept[cid] = (name, lat, lon, tz, POP_FIX.get(cid) or (max(near) if near else LEGACY_POP[cid]))
    dropped = []
    for name, lat, lon, tz, pop in rows:
        if pop < MIN_POP or name in SKIP:
            continue
        if not in_region(lat, lon):
            dropped.append(name)
            continue
        if name not in KEEP and any(km((lat, lon), (k[1], k[2])) < (METRO_KM if k[4] >= METRO_POP else MIN_KM)
               for k in kept.values()):
            continue
        kept[slug(name, kept)] = (name, lat, lon, tz, pop)
    return kept, dropped


def main(path):
    kept, dropped = select(parse(path))
    out = dict(sorted(kept.items(), key=lambda kv: (-kv[1][4], kv[1][0])))
    py = ['"""AU/NZ places for the map: id -> (name, lat, lon, IANA tz, population).',
          "",
          "Generated by build_cities.py from the GeoNames cities5000 dump (CC BY 4.0, geonames.org):",
          "every id from the first 62-city list, plus each AU/NZ place of 5,000+ people not within",
          '15 km of a larger one (30 km around cities of 250,000+), minus non-towns. Sorted by population, largest first (the app ranks markers by order)."""',
          "CITIES = {"]
    kt = []
    for cid, (n, la, lo, tz, pop) in out.items():
        py.append(f'    "{cid}": ("{n}", {la}, {lo}, "{tz}", {pop}),')
        kt.append(f'        City("{cid}", "{n}", {la}, {lo}, "{tz}", {pop}),')
    py.append("}")
    open(os.path.join(HERE, "uvpipe", "cities.py"), "w", encoding="utf-8").write("\n".join(py) + "\n")
    src = open(KT, encoding="utf-8").read()
    head, rest = src.split("    val all: List<City> = listOf(\n")
    tail = rest[rest.index("    )\n}"):]
    open(KT, "w", encoding="utf-8").write(head + "    val all: List<City> = listOf(\n" + "\n".join(kt) + "\n" + tail)
    print(len(out), "places;", len(dropped), "outside region:", dropped)


if __name__ == "__main__":
    main(sys.argv[1])
